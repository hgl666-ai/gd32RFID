#ifndef __DEBUG_CONFIG_H
#define __DEBUG_CONFIG_H

/*
 * ================================================================
 *  全局模式配置 — 本文件是唯一的配置源 (single source of truth)
 *
 *  调试版 / 生产版 只需修改下面两个宏即可全局生效,
 *  无需改动任何其他文件 (bsp_crypto.h 不再自带默认值)。
 * ================================================================
 */

/*----------------------------------------------------------------
 * 宏1: DEBUG_ENABLE — 串口调试输出总开关
 *
 *   1 = 调试/取证版:
 *       - 上电打印: [SYS] Ready | Crypto=... | SE=ONLINE/OFFLINE
 *       - SE 认证细节: ATR 长度 / 认证 SW 码
 *       - 刷卡流程各失败点一次性诊断信息 (限频, 不刷屏)
 *       注意: 调试信息与协议帧共用 USART0, 仅开发取证用
 *
 *   0 = 生产版:
 *       - 串口只传输纯二进制协议帧, 零调试输出
 *       - DBG_PRINTF 编译为空, 0 开销 0 污染
 *----------------------------------------------------------------*/
#define DEBUG_ENABLE    1

/*----------------------------------------------------------------
 * 宏2: CRYPTO_PASSTHROUGH — 加密模式开关
 *
 *   1 = 透传调试:
 *       - 跳过 SE 加密, 40 字节明文直接上传 (不依赖加密芯片)
 *       - 用于无 SE / SE 未烧录时的链路自测
 *
 *   0 = 生产加密:
 *       - 必须 SE 双向认证成功, 明文经 SE 加密后上传
 *       - 认证失败时拒绝上传 (并周期性重试认证)
 *----------------------------------------------------------------*/
#define CRYPTO_PASSTHROUGH   0

/*----------------------------------------------------------------
 * 宏3: RFID_READ_VIA_SE — 读卡方式
 *
 *   1 = 通过SE读卡 (F8P6板, 默认):
 *       FM17622 挂在 FM15L013(SE) 的 I2C 主机口上,
 *       由 SE 完成 配置读卡器/寻卡/认证/读数据 (复旦微SDK原生架构)
 *
 *   0 = MCU直连FM17622 (旧C8板):
 *       FM17622 与 SE 并挂在 MCU 的 I2C 总线上, MCU 直接寻卡/读块
 *----------------------------------------------------------------*/
#define RFID_READ_VIA_SE    1

/*----------------------------------------------------------------
 * 宏4: SE_AUTH_CRED_FROM_FLASH — SE认证凭证来源
 *
 *   0 = 固定使用 se_cmd.c 里的 SDK 示例凭证 (SDK demo 行为)
 *   1 = 使用产线数据: mcu_com_key = FLASH中的KEY(协议02下发16B),
 *       mcu_uid = 主控UID(8B折叠)
 *       (依据: 治具流程"获取uuid→获取密钥→写MCU密钥", 且 KEY=16B/UID=8B
 *        与 mcu_com_key[16]/mcu_uid[8] 尺寸完全对应;
 *        未过治具的板 KEY=EMPTY 时用示例凭证反而能认证成功)
 *----------------------------------------------------------------*/
#define SE_AUTH_CRED_FROM_FLASH   1

/*----------------------------------------------------------------
 * 关: RFID_DIAG_FULL_SWEEP — SE读卡器地址全范围扫描 (取证用)
 *
 *   1 = 诊断版启动时扫描读卡器地址 0x08~0x77 (约17秒, 阻塞串口)
 *   0 = 只试候选地址 (推荐, 默认)
 *
 *   实测记录:
 *     2026-09-16 上午: 107个地址全 0x6985 —— 但那次是**会话被污染**状态下测的, 无效!
 *     2026-09-16 15:58: **干净版复测完成: 112 个地址 found=0, 全部 0x9EFA, other=0**
 *       ⇒ 读卡器在任何 I2C 地址都不应答(干净会话逐地址复测, 结论确定)。
 *       故默认关闭, 让启动后总线保持安静(便于用示波器判断 SE 是否有后台流量)。
 *----------------------------------------------------------------*/
#define RFID_DIAG_FULL_SWEEP   0

/*----------------------------------------------------------------
 * 关: RFID_DIAG_BLINK_PROBE — "LED闪烁 + 周期性读卡器尝试" 诊断模式
 *
 *   1 = 固件进入独立循环: 每轮 LED(PA5/SYS_LED) 闪 6 下做视觉标记,
 *       紧接着发一条 set_tag_reader(0x28), 然后重新认证并等 1 秒, 如此往复。
 *       用途: 示波器测 RFID_SCL/RFID_SDA 时能明确知道"哪一段波形对应一次读卡器访问"
 *             (LED 闪完就是那一次), 不必猜时刻; 同时验证读卡器是否只是"需要更久才就绪"。
 *   0 = 正常业务流程 (默认)
 *
 *   仅诊断用: 该模式下不进正常轮询流程(串口协议仍在中断里收, 主循环也会继续处理)。
 *----------------------------------------------------------------*/
#define RFID_DIAG_BLINK_PROBE   1

#if DEBUG_ENABLE
    #include <stdio.h>
    /* 所有调用点均至少携带格式串, 直接用 __VA_ARGS__ 转发, 无需 ## 粘接 */
    #define DBG_PRINTF(...)        printf(__VA_ARGS__)
#else
    #define DBG_PRINTF(...)        ((void)0)
#endif

#endif /* __DEBUG_CONFIG_H */
